"""
quinn_discord.py — Quinn's Discord presence.

Listens for messages on a user-account self-bot, forwards them through
the local bridge server (which manages per-user history in SQLite), and
delivers Quinn's replies back to Discord with realistic typing simulation.

Full per-message flow:
  ┌─ Discord event ────────────────────────────────────────────────────┐
  │  on_message → _gate()                                              │
  │    → bridge.enqueue(user_id, display_name, text)  →  job_id       │
  │    → [typing indicator active while we wait]                       │
  │    → bridge.poll(job_id)  (SillyTavern drives generation)         │
  │    → _human_delay(reply)  (simulate realistic typing time)        │
  │    → message.reply(reply)                                          │
  └────────────────────────────────────────────────────────────────────┘

Per-user isolation:
  The bridge server stores conversation history keyed by Discord user_id
  in its SQLite `turns` table.  Each call to /v1/messages includes that
  user's previous turns.  SillyTavern's generateRaw() receives the full
  per-user history — no need to manage separate SillyTavern chats.

Config: quinn_config.json  (copy quinn_config_template.json to start)
Token : reads quinn_config["discord_token"]
        falls back to config.json["token"]  (shared with sniper)
Bridge: reads QuinnBridge/bridge/bridge_token.txt  (auto-generated by server.py)
        or quinn_config["bridge_token"]

Usage:
  python quinn_discord.py            # live mode
  python quinn_discord.py --dry-run  # filter + log, never send
"""

from __future__ import annotations

import argparse
import asyncio
import json
import logging
import math
import os
import random
import sys
import time
from pathlib import Path

import aiohttp
import discord

# ─── paths ────────────────────────────────────────────────────────────────────

ROOT         = Path(__file__).parent
QUINN_CFG    = ROOT / "quinn_config.json"
SNIPER_CFG   = ROOT / "config.json"
BRIDGE_TOKEN = ROOT / "QuinnBridge" / "bridge" / "bridge_token.txt"

log = logging.getLogger("quinn")

# ─── config ───────────────────────────────────────────────────────────────────

def _load_cfg() -> dict:
    if not QUINN_CFG.exists():
        sys.exit(
            f"[Quinn] Config not found: {QUINN_CFG}\n"
            "  Copy quinn_config_template.json → quinn_config.json and fill it in."
        )
    with QUINN_CFG.open(encoding="utf-8") as fh:
        return json.load(fh)


def _resolve_discord_token(cfg: dict) -> str:
    """Discord token: quinn_config → QUINN_DISCORD_TOKEN env → sniper config.json."""
    for source in (
        cfg.get("discord_token", "").strip(),
        os.environ.get("QUINN_DISCORD_TOKEN", "").strip(),
    ):
        if source:
            return source
    # last resort: share with sniper
    if SNIPER_CFG.exists():
        with SNIPER_CFG.open(encoding="utf-8") as fh:
            tok = json.load(fh).get("token", "").strip()
        if tok:
            log.info("Using Discord token from sniper config.json")
            return tok
    sys.exit(
        "[Quinn] No Discord token found.\n"
        "  Set discord_token in quinn_config.json,\n"
        "  or set QUINN_DISCORD_TOKEN env var,\n"
        "  or make sure config.json exists (shared with sniper)."
    )


def _resolve_bridge_token(cfg: dict) -> str:
    """Bridge token: quinn_config → QuinnBridge/bridge/bridge_token.txt."""
    explicit = cfg.get("bridge_token", "").strip()
    if explicit:
        return explicit
    if BRIDGE_TOKEN.exists():
        return BRIDGE_TOKEN.read_text(encoding="utf-8").strip()
    sys.exit(
        "[Quinn] Bridge token not found.\n"
        "  Start the bridge server first (launcher option [2] or [3]),\n"
        "  or set bridge_token in quinn_config.json."
    )

# ─── bridge client ────────────────────────────────────────────────────────────

class Bridge:
    """
    Thin async wrapper around the local bridge server REST API.

    The bridge maintains a SQLite job queue and per-user conversation turns.
    Every enqueue() call returns a job_id; poll() blocks until SillyTavern
    finishes generating and posts the reply back.
    """

    __slots__ = ("_base", "_auth", "_sess")

    def __init__(self, base_url: str, token: str):
        self._base = base_url.rstrip("/")
        self._auth = {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}
        self._sess: aiohttp.ClientSession | None = None

    async def _session(self) -> aiohttp.ClientSession:
        if self._sess is None or self._sess.closed:
            self._sess = aiohttp.ClientSession(headers=self._auth)
        return self._sess

    async def ping(self) -> bool:
        """Unauthenticated health check."""
        try:
            async with (await self._session()).get(
                f"{self._base}/health",
                timeout=aiohttp.ClientTimeout(total=3),
            ) as r:
                return r.status == 200
        except Exception:
            return False

    async def enqueue(
        self,
        user_id: str,
        display_name: str,
        message: str,
        avatar_url: str = "",
    ) -> str | None:
        """
        POST /v1/messages.
        Returns job_id on success, None on failure.
        avatar_url is the Discord CDN URL for the user's profile picture —
        the SillyTavern extension uses it when creating per-user personas.
        """
        body = {
            "user_id"     : user_id,
            "display_name": display_name,
            "message"     : message,
            "avatar_url"  : avatar_url,
        }
        try:
            async with (await self._session()).post(
                f"{self._base}/v1/messages",
                json=body,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as r:
                if r.status in (200, 202):   # bridge returns 202 Accepted
                    return (await r.json()).get("job_id")
                log.warning("Bridge enqueue → HTTP %s", r.status)
        except Exception as exc:
            log.error("Bridge enqueue error: %s", exc)
        return None

    async def poll(
        self,
        job_id: str,
        timeout: float = 120.0,
        interval: float = 1.2,
    ) -> str | None:
        """
        Poll GET /v1/jobs/{job_id} until status is 'complete' or 'failed'.
        Returns reply text or None on failure / timeout.
        """
        deadline = time.monotonic() + timeout
        sess = await self._session()
        url  = f"{self._base}/v1/jobs/{job_id}"

        while time.monotonic() < deadline:
            try:
                async with sess.get(url, timeout=aiohttp.ClientTimeout(total=8)) as r:
                    if r.status == 200:
                        data = await r.json()
                        match data.get("status"):
                            case "complete":
                                return data.get("reply")
                            case "failed":
                                log.warning("Job %s failed: %s", job_id, data.get("error"))
                                return None
            except asyncio.CancelledError:
                return None
            except Exception as exc:
                log.debug("Poll transient error (retrying): %s", exc)
            await asyncio.sleep(interval)

        log.warning("Job %s timed out after %.0fs", job_id, timeout)
        return None

    async def close(self) -> None:
        if self._sess and not self._sess.closed:
            await self._sess.close()

# ─── typing simulation ────────────────────────────────────────────────────────

async def _human_delay(reply: str, cfg: dict) -> None:
    """
    Simulate Quinn actually typing the reply before we send it.

    The typing indicator is already active from when we submitted the
    request, so Discord users see "Quinn is typing…" the whole time.
    This adds a small extra wait after generation finishes so the send
    arrives naturally — fast for short messages, longer for walls of text,
    never more than ~9 seconds regardless.

    Formula: delay = clamp(chars × rate, min, max) + small jitter
    """
    if not cfg.get("typing_simulation", True):
        return

    chars   = len(reply)
    rate    = cfg.get("typing_rate_per_char", 0.040)   # seconds per character
    min_s   = cfg.get("typing_min_seconds",    1.2)
    max_s   = cfg.get("typing_max_seconds",    9.0)

    # sigmoid-ish soft curve: long messages don't scale linearly
    raw     = chars * rate
    curved  = max_s * (1 - math.exp(-raw / max_s))
    delay   = max(min_s, min(curved, max_s))

    # ±15 % jitter so timing never looks mechanical
    jitter  = delay * random.uniform(-0.15, 0.15)
    await asyncio.sleep(max(0.5, delay + jitter))

# ─── discord client ───────────────────────────────────────────────────────────

class QuinnClient(discord.Client):
    """
    Self-bot Discord client for Quinn.

    Filtering (_gate):
      • Never own messages
      • DMs  if respond_to_dms
      • Any channel in allowed_channel_ids
      • Explicit @mention anywhere in an allowed guild
      • Guild must be in allowed_guild_ids (if that list is non-empty)
    """

    def __init__(self, cfg: dict, bridge: Bridge, dry_run: bool = False):
        super().__init__()
        self.cfg      = cfg
        self.bridge   = bridge
        self.dry_run  = dry_run

        self._guilds   = frozenset(cfg.get("allowed_guild_ids",   []))
        self._channels = frozenset(cfg.get("allowed_channel_ids", []))
        self._dms      = bool(cfg.get("respond_to_dms",      True))
        self._mentions = bool(cfg.get("respond_to_mentions",  True))

        # dedup: message_id → running task
        self._tasks: dict[int, asyncio.Task] = {}

    # ── lifecycle ──

    async def on_ready(self):
        mode = "DRY-RUN" if self.dry_run else "LIVE"
        log.info("Connected as %s (%s) [%s]", self.user, self.user.id, mode)
        print(f"[Quinn] {self.user}  [{mode}]")
        ok = await self.bridge.ping()
        print(f"[Quinn] Bridge: {'OK ✓' if ok else 'NOT REACHABLE — start bridge server first'}")

    # ── filtering ──

    def _gate(self, m: discord.Message) -> bool:
        if m.author.id == self.user.id:
            return False
        if isinstance(m.channel, discord.DMChannel):
            return self._dms
        if self._guilds and (not m.guild or m.guild.id not in self._guilds):
            return False
        if self._mentions and self.user in m.mentions:
            return True
        return bool(self._channels) and m.channel.id in self._channels

    # ── event ──

    async def on_message(self, m: discord.Message):
        if not self._gate(m) or m.id in self._tasks:
            return
        task = asyncio.create_task(self._handle(m), name=f"msg-{m.id}")
        self._tasks[m.id] = task
        task.add_done_callback(lambda _: self._tasks.pop(m.id, None))

    # ── handler ──

    async def _handle(self, m: discord.Message):
        # Grab identifying info before any awaits
        uid    = str(m.author.id)
        name   = m.author.display_name
        text   = m.content.strip()
        avatar = str(m.author.avatar.url) if m.author.avatar else ""
        if not text:
            return

        log.info("← [%s] %s: %r", uid, name, text[:100])

        if self.dry_run:
            print(f"[Quinn/dry] {name} ({uid}): {text[:60]!r}")
            return

        # ── enqueue to bridge ──
        job_id = await self.bridge.enqueue(uid, name, text, avatar_url=avatar)
        if not job_id:
            log.warning("Enqueue failed for %s — bridge down?", name)
            return

        timeout = float(self.cfg.get("reply_timeout_seconds", 120))

        # ── wait for generation, typing indicator active the whole time ──
        try:
            async with m.channel.typing():
                reply = await self.bridge.poll(job_id, timeout=timeout)
                if reply:
                    # natural delay after generation finishes
                    await _human_delay(reply, self.cfg)
        except Exception as exc:
            log.error("Error waiting on job %s: %s", job_id, exc)
            return

        # ── deliver ──
        if reply:
            try:
                await m.reply(reply, mention_author=False)
                log.info("→ [%s] %s (job %s, %d chars)", uid, name, job_id, len(reply))
            except discord.Forbidden:
                log.warning(
                    "No permission to reply in channel %s (%s) — "
                    "Quinn lacks Send Messages / Read Message History.",
                    m.channel.id, getattr(m.channel, "name", "DM"),
                )
            except discord.HTTPException as exc:
                log.error("Discord send error (HTTP %s): %s", exc.status, exc)
        else:
            log.warning("No reply for job %s (timeout or bridge failure)", job_id)

    # ── shutdown ──

    async def close(self):
        for t in list(self._tasks.values()):
            t.cancel()
        await self.bridge.close()
        await super().close()

# ─── entry ────────────────────────────────────────────────────────────────────

async def _run(cfg: dict, dry_run: bool) -> None:
    token        = _resolve_discord_token(cfg)
    bridge_token = _resolve_bridge_token(cfg)
    bridge_url   = cfg.get("bridge_url", "http://127.0.0.1:8765")

    bridge = Bridge(bridge_url, bridge_token)
    client = QuinnClient(cfg, bridge, dry_run=dry_run)

    try:
        await client.start(token)
    except discord.LoginFailure:
        sys.exit("[Quinn] Discord login failed — check your token.")
    except KeyboardInterrupt:
        pass
    finally:
        if not client.is_closed():
            await client.close()


def main() -> None:
    ap = argparse.ArgumentParser(description="Quinn — Discord AI character client")
    ap.add_argument("--dry-run", action="store_true",
                    help="Log filtered messages but never send Discord replies")
    ap.add_argument("--log", default="INFO",
                    choices=["DEBUG", "INFO", "WARNING", "ERROR"],
                    help="Log level")
    args = ap.parse_args()

    logging.basicConfig(
        level=getattr(logging, args.log),
        format="%(asctime)s [%(name)s] %(levelname)s %(message)s",
    )

    cfg = _load_cfg()
    asyncio.run(_run(cfg, dry_run=args.dry_run))


if __name__ == "__main__":
    main()